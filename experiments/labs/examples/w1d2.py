# 学习目标：列表切片与引用
# 使用方式：先预测输出，再运行；最后只改一个输入并解释变化。
# 输出核对：三档预算、前两项[8,16]、共享列表[1,2]。
# 列表保存三档采样预算
budgets = [8, 16, 32]
# 字典用名称关联种子和预算列表
config = {"seed": 7, "budgets": budgets}
# 按键取出列表后逐项遍历
for n in config["budgets"]:
    # 每轮打印一档预算
    print("预算:", n)
# 切片[:2]包括索引0和1，不包括2
print("前两项:", budgets[:2])
# 创建新的可变列表
a = [1]
# b和a引用同一对象，不是复制
b = a
# 通过b修改对象也会影响a
b.append(2)
# 观察共享引用
print("共享列表:", a)
# 验证a也被修改；独立副本可用a.copy()
assert a == [1, 2]
