# 学习目标：比较数字与字符串
# 使用方式：先预测输出，再运行；最后只改一个输入并解释变化。
# 输出核对：依次为8、44、8、True。注意第二行是字符串。
# a保存整数4，可以进行数值运算
a = 4
# 引号让4成为文本，不是数值
b = "4"
# 整数乘2是算术乘法，得到8
print(a * 2)
# 字符串乘2是重复拼接，得到44
print(b * 2)
# int把文本4转换为整数后再相加
print(a + int(b))
# abs取绝对值，用容差比较浮点数而非要求完全相等
print(abs(0.1 + 0.2 - 0.3) < 1e-9)
# and要求两个条件同时成立
assert a * 2 == 8 and b * 2 == "44"
