# 学习目标：一致性零空间反例
# 使用方式：先预测输出，再运行；最后只改一个输入并解释变化。
# 输出核对：三个不同向量的观测残差都0。
# 定义观测函数，对应线性算子A
def observe(x):
    # 只观察第一个分量，第二个落在零空间
    return x[0]  # A=[1,0]
# 观测真值为1
y = 1.
# 依次尝试第二分量不同的三个候选
for x in ([1., 0.], [1., 100.], [1., -7.]):
    # 观测空间的残差，与清晰空间误差不同
    residual = (observe(x)-y)**2
    # 打印候选及残差
    print(x, "残差:", residual)
    # 三个残差都0，反驳残差0就一定恢复正确
    assert residual == 0
