# 学习目标：不依赖库手算矩阵乘法
# 使用方式：先预测输出，再运行；最后只改一个输入并解释变化。
# 输出核对：矩阵乘向量为[5,11]，点积为2。
# a是两行两列的矩阵，以嵌套列表表示
a = [[1, 2], [3, 4]]
# x是长度2的列向量，用列表保存
x = [1, 2]
# 外层逐行；zip配对行元素和x；内层乘积求和得到一个输出分量
y = [sum(v * w for v, w in zip(row, x)) for row in a]
# 矩阵乘向量得到长度2的列表
print("矩阵乘向量:", y)
# 两个长度2向量对应相乘再求和
print("点积:", sum(v * w for v, w in zip([2, -1], [3, 4])))
# 检查两个输出分量均正确
assert y == [5, 11]
