# 学习目标：一次梯度下降
# 使用方式：先预测输出，再运行；最后只改一个输入并解释变化。
# 输出核对：参数2.18、1.06，损失约5.76。把rate改成.2观察差别。
# 定义参数、输入和目标
w, b, x, target = 2.0, 1.0, 3.0, 10.0
# rate是学习率，控制每次更新幅度
rate = 0.01
# 先算当前预测减目标的残差
error = w * x + b - target
# 链式法则给权重与偏置各自的梯度
dw, db = 2 * error * x, 2 * error
# 两个右侧都用更新前的参数，再同时赋值
w, b = w - rate * dw, b - rate * db
# 查看新参数
print("更新后参数:", w, b)
# 用更新后的参数重新计算损失
print("更新后损失:", (w * x + b - target) ** 2)
# 验证权重更新，学习率过大不保证下降
assert abs(w - 2.18) < 1e-12
