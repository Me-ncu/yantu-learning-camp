# 学习目标：高斯后验参数
# 使用方式：先预测输出，再运行；最后只改一个输入并解释变化。
# 输出核对：均值.6、方差.03125。
# mu是先验均值，tau是先验标准差，sigma是观测噪声标准差，y是观测
mu, tau, sigma, y = 0.5, 0.25, 0.25, 0.7
# 标准差先平方，再代入高斯共轭后验方差公式
variance = tau**2*sigma**2/(tau**2+sigma**2)
# 按两类方差加权得到均值，它是平方误差意义下的最优估计
mean = (sigma**2*mu+tau**2*y)/(tau**2+sigma**2)
# 打印均值与方差；方差不是质量达标概率
print("后验均值:", mean, "后验方差:", variance)
# 同时校验均值和方差；本例假设先验与似然都为高斯
assert abs(mean-.6) < 1e-12 and variance == .03125
